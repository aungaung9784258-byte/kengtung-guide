import 'dart:ui' as ui;

import 'package:flutter/material.dart';

import '../../../app/theme/app_motion.dart';

/// ---------------------------------------------------------------------------
/// FrostedPhoto
///
/// A photo with two things on top of it:
///   1. a parallax drift, driven by the scroll position of whatever scrollable
///      it happens to live inside, and
///   2. a frosted band along the bottom, so the caption stays readable no
///      matter how bright or busy the photo is.
///
/// The band is a *progressive* blur: three stacked BackdropFilters of
/// increasing sigma. A single blurred rectangle leaves a hard edge where the
/// blur stops; stacking them makes the transition invisible.
///
/// Reusable anywhere a caption sits on a photo — place detail, village cards.
/// ---------------------------------------------------------------------------
class FrostedPhoto extends StatefulWidget {
  const FrostedPhoto({
    super.key,
    required this.image,
    required this.height,
    this.parallax = 0.16,
    this.caption,
    this.disclaimer,
    this.borderRadius = BorderRadius.zero,
    this.bandHeight,
    this.captionStyle,
    this.semanticLabel,
  });

  final String image;
  final double height;

  /// 0.0 = pinned, 0.30 = drifts a lot. Comes from the JSON per figure.
  final double parallax;
  final String? caption;

  /// Small italic line under the caption (e.g. "generated by AI").
  final String? disclaimer;
  final BorderRadius borderRadius;

  /// Defaults to 45% of [height].
  final double? bandHeight;
  final TextStyle? captionStyle;
  final String? semanticLabel;

  @override
  State<FrostedPhoto> createState() => _FrostedPhotoState();
}

class _FrostedPhotoState extends State<FrostedPhoto> {
  ScrollPosition? _position;
  double _shift = 0;

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    _position?.removeListener(_onScroll);
    _position = Scrollable.maybeOf(context)?.position;
    _position?.addListener(_onScroll);
    WidgetsBinding.instance.addPostFrameCallback((_) => _onScroll());
  }

  @override
  void dispose() {
    _position?.removeListener(_onScroll);
    super.dispose();
  }

  void _onScroll() {
    if (!mounted) return;
    final box = context.findRenderObject() as RenderBox?;
    final scrollBox =
        Scrollable.maybeOf(context)?.context.findRenderObject() as RenderBox?;
    if (box == null || scrollBox == null || !box.hasSize) return;

    // How far this photo's centre is from the centre of the viewport.
    final selfCentre =
        box.localToGlobal(box.size.center(Offset.zero), ancestor: scrollBox).dy;
    final viewportCentre = scrollBox.size.height / 2;
    final next = (selfCentre - viewportCentre) * -widget.parallax;

    if ((next - _shift).abs() > 0.3) setState(() => _shift = next);
  }

  @override
  Widget build(BuildContext context) {
    final band = widget.bandHeight ?? widget.height * 0.45;
    // The image is taller than its frame so there is room to drift.
    final overscan = widget.height * widget.parallax * 2.2;

    return ClipRRect(
      borderRadius: widget.borderRadius,
      child: SizedBox(
        height: widget.height,
        width: double.infinity,
        child: Stack(
          fit: StackFit.expand,
          children: [
            // ---- the photo, drifting ----
            Positioned(
              left: 0,
              right: 0,
              top: -overscan / 2 + _shift,
              height: widget.height + overscan,
              child: Image.asset(
                widget.image,
                fit: BoxFit.cover,
                semanticLabel: widget.semanticLabel ?? widget.caption,
                errorBuilder: (_, __, ___) => const ColoredBox(
                  color: Color(0xFF1A2A25),
                  child: Center(
                    child: Icon(Icons.image_not_supported_outlined,
                        color: Colors.white24, size: 28),
                  ),
                ),
              ),
            ),

            // ---- frosted band ----
            Positioned(
              left: 0,
              right: 0,
              bottom: 0,
              height: band,
              child: IgnorePointer(
                child: Stack(
                  fit: StackFit.expand,
                  children: [
                    _blurBand(height: band, sigma: 2),
                    _blurBand(height: band * 0.70, sigma: 7),
                    _blurBand(height: band * 0.44, sigma: 15),
                    // Dim on top of the blur, so white skies stay readable.
                    DecoratedBox(
                      decoration: const BoxDecoration(
                        gradient: LinearGradient(
                          begin: Alignment.topCenter,
                          end: Alignment.bottomCenter,
                          colors: [
                            Color(0x00060C0A),
                            Color(0x4D060C0A),
                            Color(0x9E060C0A),
                            Color(0xCC060C0A),
                          ],
                          stops: [0.0, 0.42, 0.78, 1.0],
                        ),
                      ),
                    ),
                  ],
                ),
              ),
            ),

            // ---- caption ----
            if (widget.caption != null && widget.caption!.isNotEmpty)
              Positioned(
                left: 18,
                right: 18,
                bottom: 14,
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    Text(
                      widget.caption!,
                      style: widget.captionStyle ??
                          const TextStyle(
                            color: Colors.white,
                            fontSize: 12,
                            height: 1.45,
                            fontWeight: FontWeight.w600,
                            shadows: [
                              Shadow(
                                  color: Color(0x8C000000),
                                  blurRadius: 4,
                                  offset: Offset(0, 1)),
                            ],
                          ),
                    ),
                    if (widget.disclaimer != null &&
                        widget.disclaimer!.isNotEmpty) ...[
                      const SizedBox(height: 4),
                      Text(
                        widget.disclaimer!,
                        style: const TextStyle(
                          color: Color(0xCCFFFFFF),
                          fontSize: 10,
                          height: 1.4,
                          fontStyle: FontStyle.italic,
                        ),
                      ),
                    ],
                  ],
                ),
              ),
          ],
        ),
      ),
    );
  }

  Widget _blurBand({required double height, required double sigma}) {
    return Align(
      alignment: Alignment.bottomCenter,
      child: SizedBox(
        height: height,
        width: double.infinity,
        child: ClipRect(
          child: BackdropFilter(
            filter: ui.ImageFilter.blur(sigmaX: sigma, sigmaY: sigma),
            child: const SizedBox.expand(),
          ),
        ),
      ),
    );
  }
}

/// The cover at the top of the About page. Same frosted idea, but the text
/// block is bigger and the image drifts harder.
class FrostedCover extends StatelessWidget {
  const FrostedCover({
    super.key,
    required this.image,
    required this.kicker,
    required this.title,
    required this.subtitle,
    this.parallax = 0.30,
    this.height = 420,
  });

  final String image;
  final String kicker;
  final String title;
  final String subtitle;
  final double parallax;
  final double height;

  @override
  Widget build(BuildContext context) {
    return Stack(
      children: [
        FrostedPhoto(
          image: image,
          height: height,
          parallax: parallax,
          bandHeight: height * 0.52,
        ),
        Positioned(
          left: 22,
          right: 22,
          bottom: 34,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            mainAxisSize: MainAxisSize.min,
            children: [
              Text(
                kicker.toUpperCase(),
                style: const TextStyle(
                  color: Color(0xE6FFFFFF),
                  fontSize: 11,
                  letterSpacing: 2.2,
                  fontWeight: FontWeight.w700,
                ),
              ),
              const SizedBox(height: 8),
              Text(
                title,
                style: const TextStyle(
                  color: Colors.white,
                  fontSize: 38,
                  height: 1.1,
                  fontWeight: FontWeight.w800,
                ),
              ),
              const SizedBox(height: 8),
              Text(
                subtitle,
                style: const TextStyle(
                  color: Color(0xDEFFFFFF),
                  fontSize: 13.5,
                  height: 1.5,
                ),
              ),
            ],
          ),
        ),
        Positioned(
          left: 0,
          right: 0,
          bottom: 10,
          child: _ScrollCue(),
        ),
      ],
    );
  }
}

class _ScrollCue extends StatefulWidget {
  @override
  State<_ScrollCue> createState() => _ScrollCueState();
}

class _ScrollCueState extends State<_ScrollCue>
    with SingleTickerProviderStateMixin {
  late final AnimationController _c = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 1400),
  )..repeat(reverse: true);

  @override
  void dispose() {
    _c.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return FadeTransition(
      opacity: Tween(begin: 0.35, end: 0.9)
          .animate(CurvedAnimation(parent: _c, curve: AppMotion.gentle)),
      child: SlideTransition(
        position: Tween(begin: Offset.zero, end: const Offset(0, 0.35))
            .animate(CurvedAnimation(parent: _c, curve: AppMotion.gentle)),
        child: const Icon(Icons.keyboard_arrow_down_rounded,
            color: Colors.white, size: 26),
      ),
    );
  }
}
