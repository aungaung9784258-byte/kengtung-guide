/// One numbered block of the page. `type` decides how it is drawn.
@immutable
class AboutSection {
  const AboutSection({
    required this.id,
    required this.number,
    required this.type,
    required this.title,
    required this.body,
    required this.stats,
    required this.timeline,
    required this.names,
    required this.pills,
    required this.landmarks,
    required this.rows,
    required this.pair,
    this.note,
    this.figure,
    this.cta,
    this.disclaimer,
  });

  final String id;
  final String number;

  /// stats | prose | timeline | pills | landmarks | rows
  final String type;
  final L10nText title;
  final List<L10nText> body;
  final List<AboutStat> stats;
  final List<AboutTimelineEntry> timeline;
  final List<AboutNameForm> names;
  final List<String> pills;
  final List<AboutLandmark> landmarks;
  final List<AboutRow> rows;
  final List<AboutFigure> pair;
  final L10nText? note;
  final AboutFigure? figure;
  final AboutCta? cta;
  final L10nText? disclaimer;

  factory AboutSection.fromJson(Map<String, dynamic> json) {
    List<Map<String, dynamic>> maps(String key) =>
        (json[key] as List?)?.whereType<Map<String, dynamic>>().toList() ??
        const [];

    return AboutSection(
      id: json['id'] as String? ?? '',
      number: json['number'] as String? ?? '',
      type: json['type'] as String? ?? 'prose',
      title: L10nText.fromJson(json['title']),
      body: (json['body'] as List?)
              ?.map((e) => L10nText.fromJson(e))
              .toList() ??
          const [],
      stats: maps('stats').map(AboutStat.fromJson).toList(),
      timeline: maps('timeline').map(AboutTimelineEntry.fromJson).toList(),
      names: maps('names').map(AboutNameForm.fromJson).toList(),
      pills: (json['pills'] as List?)?.whereType<String>().toList() ?? const [],
      landmarks: maps('landmarks').map(AboutLandmark.fromJson).toList(),
      rows: maps('rows').map(AboutRow.fromJson).toList(),
      pair: maps('pair')
          .map(AboutFigure.fromJson)
          .whereType<AboutFigure>()
          .toList(),
      note: json['note'] == null ? null : L10nText.fromJson(json['note']),
      figure: AboutFigure.fromJson(json['figure'] as Map<String, dynamic>?),
      cta: AboutCta.fromJson(json['cta'] as Map<String, dynamic>?),
      disclaimer: json['disclaimer'] == null
          ? null
          : L10nText.fromJson(json['disclaimer']),
    );
  }
}

