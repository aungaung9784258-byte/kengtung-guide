@immutable
class AboutContent {
  const AboutContent({
    required this.version,
    required this.lastUpdated,
    required this.cover,
    required this.sections,
    required this.sources,
  });

  final int version;
  final String lastUpdated;
  final AboutCover cover;
  final List<AboutSection> sections;
  final AboutSources sources;

  factory AboutContent.fromJson(Map<String, dynamic> json) => AboutContent(
        version: (json['version'] as num?)?.toInt() ?? 1,
        lastUpdated: json['lastUpdated'] as String? ?? '',
        cover: AboutCover.fromJson(
            (json['cover'] as Map<String, dynamic>?) ?? const {}),
        sections: (json['sections'] as List?)
                ?.whereType<Map<String, dynamic>>()
                .map(AboutSection.fromJson)
                .toList() ??
            const [],
        sources: AboutSources.fromJson(
            json['sources'] as Map<String, dynamic>?),
      );
}
