import 'package:flutter/foundation.dart';

import 'place.dart' show L10nText;

/// ---------------------------------------------------------------------------
/// Models for assets/data/about_kengtung.json
///
/// NOTE: nothing here touches existing models. `L10nText` is reused from
/// place.dart so there is only ever one bilingual string type in the app.
/// ---------------------------------------------------------------------------

/// How sure we are about a fact. Printed as a coloured dot on the timeline.
enum AboutConfidence {
  verified,
  estimated,
  legend;

  static AboutConfidence parse(String? raw) {
    switch (raw) {
      case 'estimated':
        return AboutConfidence.estimated;
      case 'legend':
        return AboutConfidence.legend;
      default:
        return AboutConfidence.verified;
    }
  }
}

/// A photo inside the page, with its own parallax strength and caption.
@immutable
class AboutFigure {
  const AboutFigure({
    required this.image,
    required this.parallax,
    required this.caption,
    this.disclaimer,
  });

  final String image;

  /// 0.0 = pinned to the page, 0.3 = drifts a lot. Tune per figure.
  final double parallax;
  final L10nText caption;

  /// Shown in small italic under the caption, e.g. "generated by AI".
  /// Delete the key from the JSON once a real photograph is in place.
  final L10nText? disclaimer;

  static AboutFigure? fromJson(Map<String, dynamic>? json) {
    if (json == null) return null;
    final image = json['image'] as String?;
    if (image == null || image.isEmpty) return null;
    return AboutFigure(
      image: image,
      parallax: (json['parallax'] as num?)?.toDouble() ?? 0.16,
      caption: L10nText.fromJson(json['caption']),
      disclaimer: json['disclaimer'] == null
          ? null
          : L10nText.fromJson(json['disclaimer']),
    );
  }
}

